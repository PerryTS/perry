// The perry-stdlib bundle in the WASIp2 runtime archive: web streams,
// webcrypto digests, node:crypto random bytes and the http2 module all link
// and run under --target wasi, as they do under --target wasip1.
import { ReadableStream } from "node:stream/web";
import { randomBytes, webcrypto } from "node:crypto";
import * as http2 from "node:http2";

async function main(): Promise<void> {
  const stream = new ReadableStream<string>({
    start(controller) {
      controller.enqueue("a");
      controller.enqueue("b");
      controller.close();
    },
  });
  const reader = stream.getReader();
  let text = "";
  for (;;) {
    const { done, value } = await reader.read();
    if (done) break;
    text += value;
  }
  console.log("stream", text);

  const digest = await webcrypto.subtle.digest("SHA-256", new TextEncoder().encode("perry"));
  console.log("digest", Buffer.from(digest).toString("hex"));

  const bytes = randomBytes(16);
  console.log("random", bytes.length);

  console.log("http2", typeof http2.createSecureServer, typeof http2.constants.HTTP2_HEADER_PATH);
}

main();
