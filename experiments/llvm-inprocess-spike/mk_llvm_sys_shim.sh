#!/bin/bash
# Build an LLVM_SYS_221_PREFIX shim for a downloaded upstream LLVM release.
#
#   ./mk_llvm_sys_shim.sh ~/opt/LLVM-22.1.8-Linux-X64 ~/opt/llvm22-shim
#   export LLVM_SYS_221_PREFIX=~/opt/llvm22-shim
#
# Why this exists: on a distro with no LLVM 22 package (Fedora 43 stops at
# llvm20-devel; its system libs are 21), the upstream release tarball is the
# only route. But those tarballs are built on Ubuntu, and `llvm-config
# --system-libs` reports the BUILD HOST's static system libraries by absolute
# path -- e.g. /usr/lib/x86_64-linux-gnu/libzstd.a, which exists on no other
# distro. llvm-sys's build script panics on any --system-libs entry that is
# neither `-lfoo` nor an existing file:
#
#   Unable to parse result of llvm-config --system-libs: /usr/.../libzstd.a
#
# so the build dies before compiling anything. This wrapper rewrites exactly
# those dangling absolute paths to plain `-lname` flags, letting the linker
# resolve them against the host's own shared libraries. Entries that DO exist
# are left alone -- llvm-sys handles a real absolute path fine, and silently
# converting a deliberate static link into a dynamic one would be a change we
# were not asked to make.
#
# Everything else passes through untouched, including every path query: the
# real llvm-config still answers those relative to its own prefix, so the shim
# needs no lib/ or include/ of its own.
set -euo pipefail

REAL=${1:?usage: mk_llvm_sys_shim.sh <real-llvm-prefix> <shim-prefix>}
SHIM=${2:?usage: mk_llvm_sys_shim.sh <real-llvm-prefix> <shim-prefix>}
REAL=$(cd "$REAL" && pwd)

[ -x "$REAL/bin/llvm-config" ] || { echo "no llvm-config under $REAL/bin" >&2; exit 1; }

mkdir -p "$SHIM/bin"
cat > "$SHIM/bin/llvm-config" <<EOF
#!/bin/bash
# Generated by mk_llvm_sys_shim.sh -- see that script for the rationale.
set -uo pipefail
out=\$("$REAL/bin/llvm-config" "\$@") || exit \$?
printf '%s\n' "\$out" | awk '{
  for (i = 1; i <= NF; i++) {
    if (\$i ~ /^\// && system("test -e \"" \$i "\"") != 0) {
      lib = \$i
      sub(/.*\//, "", lib)          # basename
      sub(/^lib/, "", lib)
      sub(/\.(a|so|dylib|tbd)(\..*)?\$/, "", lib)
      \$i = "-l" lib
    }
  }
  print
}'
EOF
chmod +x "$SHIM/bin/llvm-config"

echo "shim written: $SHIM/bin/llvm-config -> $REAL/bin/llvm-config"
echo "  --version:     $("$SHIM/bin/llvm-config" --version)"
echo "  --libdir:      $("$SHIM/bin/llvm-config" --libdir)"
echo "  --system-libs: $("$SHIM/bin/llvm-config" --system-libs --link-static)"
echo
echo "export LLVM_SYS_221_PREFIX=$SHIM"
