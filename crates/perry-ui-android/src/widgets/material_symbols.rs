//! SF Symbol names → Material Icons (Round) ligatures.
//!
//! `ImageSymbol(name)` on Android draws the glyph from the Material Icons
//! Round font bundled in the APK (`assets/perry/MaterialIconsRound-Regular.otf`,
//! Apache 2.0), so apps that use SF Symbol names get real icons instead of
//! emoji. The font renders a ligature name (`"chevron_right"`) as its icon.

/// Ligature for an SF Symbol name, trying the exact name first and then the
/// name without its `.fill` / `.circle` / `.square` style suffixes.
pub fn ligature(name: &str) -> Option<&'static str> {
    let mut n = name;
    loop {
        if let Some(l) = exact(n) {
            return Some(l);
        }
        let stripped = [".fill", ".circle", ".square", ".rectangle", ".badge"]
            .iter()
            .find_map(|s| n.strip_suffix(s));
        match stripped {
            Some(s) => n = s,
            None => return None,
        }
    }
}

