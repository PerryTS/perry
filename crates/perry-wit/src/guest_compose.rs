//! Keep the original guest and its synchronous facade as sibling instances.
//! Only functions are replaced; every resource and value type is re-exported
//! from the original instance, preserving nominal identity across interfaces.
use crate::guest_c::facade::Plan;
use anyhow::{ensure, Context, Result};
use std::collections::{BTreeMap, HashMap};
use wac_graph::{
    types::{ItemKind, Package},
    CompositionGraph, EncodeOptions, NodeId,
};
use wasm_encoder::{Component, ComponentExportSection, ComponentInstanceSection, RawSection};
use wasmparser::{ComponentExternalKind as Kind, Parser, Payload, Validator, WasmFeatures};
#[cfg(test)]
mod tests;

struct Export {
    name: String,
    fields: Option<Vec<(String, String)>>,
    item: String,
}

/// Compose files generated by the experimental guest entry point. The facade
/// must be linked as its own component; concatenating its core module with the
/// guest would violate canonical adapter instance ancestry requirements.
#[doc(hidden)]
pub fn compose_experimental_guest(producer: &[u8], facade: &[u8], plan: &[u8]) -> Result<Vec<u8>> {
    let plan: Plan = serde_json::from_slice(plan)?;
    ensure!(plan.schema_version == 1, "Unsupported producer facade plan");
    let mut graph = CompositionGraph::new();
    let package = Package::from_bytes("perry:producer", None, producer, graph.types_mut())?;
    let original_exports = graph.types()[package.ty()].exports.clone();
    ensure!(
        original_exports.contains_key(&plan.actor) && original_exports.contains_key(&plan.signal),
        "Missing generated producer actor"
    );
    let producer = graph.register_package(package)?;
    let package = Package::from_bytes("perry:facade", None, facade, graph.types_mut())?;
    let facade = graph.register_package(package)?;
    let producer = graph.instantiate(producer);
    let facade = graph.instantiate(facade);
    // Bind original interfaces first: later root function signatures can refer
    // to their nominal resource aliases.
    for interface_pass in [true, false] {
        for binding in &plan.imports {
            let ty = original_exports
                .get(&binding.original)
                .context("Missing original facade import")?;
            if matches!(ty, ItemKind::Instance(_)) != interface_pass {
                continue;
            }
            let value = graph.alias_instance_export(producer, &binding.original)?;
            graph.set_instantiation_argument(facade, &binding.local, value)?;
        }
    }
    let mut temporary = HashMap::<NodeId, String>::new();
    fn expose(
        graph: &mut CompositionGraph,
        names: &mut HashMap<NodeId, String>,
        node: NodeId,
    ) -> Result<String> {
        if let Some(name) = names.get(&node) {
            return Ok(name.clone());
        }
        let name = format!("perry-item-{}", names.len());
        graph.export(node, &name)?;
        names.insert(node, name.clone());
        Ok(name)
    }
    let mut exports = Vec::new();
    for (name, kind) in original_exports {
        if name == plan.actor || name == plan.signal {
            continue;
        }
        let original = graph.alias_instance_export(producer, &name)?;
        if let ItemKind::Instance(id) = kind {
            let fields = graph.types()[id]
                .exports
                .keys()
                .cloned()
                .collect::<Vec<_>>();
            let mut members = Vec::new();
            for field in fields {
                let node = if let Some(forward) = plan
                    .forwards
                    .iter()
                    .find(|f| f.interface == name && f.function == field)
                {
                    graph.alias_instance_export(facade, &forward.export)?
                } else {
                    graph.alias_instance_export(original, &field)?
                };
                members.push((field, expose(&mut graph, &mut temporary, node)?));
            }
            exports.push(Export {
                name,
                fields: Some(members),
                item: String::new(),
            });
        } else {
            let node = if let Some(forward) = plan
                .forwards
                .iter()
                .find(|f| f.interface.is_empty() && f.function == name)
            {
                graph.alias_instance_export(facade, &forward.export)?
            } else {
                original
            };
            exports.push(Export {
                name,
                fields: None,
                item: expose(&mut graph, &mut temporary, node)?,
            });
        }
    }
    let encoded = graph.encode(EncodeOptions::default())?;
    publish(&encoded, &exports)
}

fn publish(encoded: &[u8], exports: &[Export]) -> Result<Vec<u8>> {
    let mut output = Component::new();
    let mut items = BTreeMap::<String, (Kind, u32)>::new();
    let mut depth = 0;
    let mut exported = false;
    for payload in Parser::new(0).parse_all(encoded) {
        let payload = payload?;
        if depth > 0 {
            match payload {
                Payload::ModuleSection { .. } | Payload::ComponentSection { .. } => depth += 1,
                Payload::End(_) => depth -= 1,
                _ => {}
            }
            continue;
        }
        if let Payload::ComponentExportSection(section) = &payload {
            exported = true;
            for export in section.clone() {
                let export = export?;
                ensure!(
                    export.ty.is_none(),
                    "Unexpected typed temporary facade export"
                );
                items.insert(export.name.name.into(), (export.kind, export.index));
            }
            continue;
        }
        if let Some((id, range)) = payload.as_section() {
            // Graph aliases are encoded before all temporary exports. Removing
            // those exports must not invalidate references from later code.
            ensure!(!exported || id == 0, "Code after temporary facade exports");
            output.section(&RawSection {
                id,
                data: &encoded[range],
            });
        }
        if matches!(
            payload,
            Payload::ModuleSection { .. } | Payload::ComponentSection { .. }
        ) {
            depth += 1;
        }
    }
    let types =
        Validator::new_with_features(WasmFeatures::all()).validate_all(output.as_slice())?;
    let mut instances = types.as_ref().component_instance_count();
    let mut public = ComponentExportSection::new();
    for export in exports {
        if let Some(fields) = &export.fields {
            let fields = fields
                .iter()
                .map(|(name, item)| {
                    let (kind, index) = items.get(item).context("Missing facade field alias")?;
                    Ok((name.as_str(), (*kind).into(), *index))
                })
                .collect::<Result<Vec<_>>>()?;
            let mut section = ComponentInstanceSection::new();
            section.export_items(fields);
            output.section(&section);
            public.export(
                export.name.as_str(),
                wasm_encoder::ComponentExportKind::Instance,
                instances,
                None,
            );
            instances += 1;
        } else {
            let (kind, index) = items
                .get(&export.item)
                .context("Missing facade export alias")?;
            public.export(export.name.as_str(), (*kind).into(), *index, None);
        }
    }
    output.section(&public);
    let bytes = output.finish();
    Validator::new_with_features(WasmFeatures::all()).validate_all(&bytes)?;
    Ok(bytes)
}
