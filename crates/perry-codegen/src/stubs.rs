//! Stub object generation for unresolved imports — LLVM port.
//!
//! This is the LLVM equivalent of `crates/perry-codegen/src/stubs.rs`.
//! It produces a `.o` containing dummy globals/functions for symbols that
//! the linker would otherwise fail on (missing imports from native modules
//! that the user doesn't actually use, identity pass-throughs for runtime
//! helpers absent in standalone mode, etc.).
//!
//! The strategy: emit a tiny LLVM IR text snippet and feed it to the
//! existing `compile_ll_to_object` shellout. No special-case in the rest
//! of the pipeline — the result is a normal object file.

use crate::module::LlModule;
use crate::types::VOID;
use anyhow::Result;

use crate::linker::compile_ll_to_object;
use crate::nanbox::TAG_UNDEFINED;

/// Generate a stub object file for missing symbols from unresolved imports.
///
/// Four kinds of stubs are produced:
///
/// 1. **Data symbols** — exported `i64` globals initialized to NaN-boxed
///    `TAG_UNDEFINED`. Used when an `extern` data slot is referenced but
///    the providing module isn't linked.
/// 2. **Function symbols** — `double()` functions that return NaN-boxed
///    `TAG_UNDEFINED`. Used for nullary helpers in standalone mode.
/// 3. **Identity functions** — `double(double)` functions that pass their
///    argument through unchanged. Used for `js_await_any_promise` and
///    similar pass-through points where the V8 runtime is not present.
/// 4. **Closure-wrapper symbols** — `double(i64, i64, double, double,
///    double, double, double)` functions returning NaN-boxed `TAG_UNDEFINED`.
///    The JS body ABI (`perry_abi::JS_BODY_*`: callee, receiver, arguments)
///    of the wrappers cross-module function-VALUE references name
///    (`__perry_wrap_perry_fn_<src>__<name>`).
///    Used when a non-entry module fails to compile under `--allow-unimplemented`
///    so the link still succeeds; consumers that read the import as a closure
///    handle observe a singleton wrapping the undefined-return stub.
///
/// `target` is a Perry short target name (`macos`, `ios`, `android`,
/// `linux`, `windows`, …) and is forwarded to clang via `-target` so the
/// emitted object matches the rest of the link.
pub fn generate_stub_object(
    missing_data_symbols: &[String],
    missing_func_symbols: &[String],
    identity_func_symbols: &[String],
    target: Option<&str>,
) -> Result<Vec<u8>> {
    generate_stub_object_full(
        missing_data_symbols,
        missing_func_symbols,
        identity_func_symbols,
        &[],
        target,
    )
}

/// Same as [`generate_stub_object`], plus a fourth bucket for closure-
/// wrapper symbols. Split out so the existing 3-arg callers don't break.
pub fn generate_stub_object_full(
    missing_data_symbols: &[String],
    missing_func_symbols: &[String],
    identity_func_symbols: &[String],
    wrapper_func_symbols: &[String],
    target: Option<&str>,
) -> Result<Vec<u8>> {
    let mut ll = String::new();

    // Module header. We do not emit a target triple here — clang infers it
    // from `-target` (set below) and from the host otherwise. Leaving it
    // unspecified avoids a "warning: overriding the module target triple"
    // when the caller passes a non-host target.
    ll.push_str("; Perry stub object — generated by perry-codegen::stubs\n");
    ll.push_str("; All stubs use NaN-boxed TAG_UNDEFINED as their value.\n\n");

    // LLVM IR double constants are hex bit patterns: `0x` followed by 16
    // hex digits, interpreted as the f64's IEEE 754 bit pattern. NaN-boxed
    // undefined is u64 0x7FFC000000000001.
    let undef_hex = format!("0x{:016X}", TAG_UNDEFINED);

    // 1. Data symbols — i64 globals (the runtime treats the slot as a raw
    //    bit pattern and re-interprets via NaN-box accessors).
    for name in missing_data_symbols {
        // global i64 with TAG_UNDEFINED bit pattern
        ll.push_str(&format!(
            "@{} = global i64 {}, align 8\n",
            name, TAG_UNDEFINED as i64
        ));
    }
    if !missing_data_symbols.is_empty() {
        ll.push('\n');
    }

    // 2. Nullary function stubs — `double name()` returning TAG_UNDEFINED.
    for name in missing_func_symbols {
        ll.push_str(&format!(
            "define double @{}() {{\n  ret double {}\n}}\n\n",
            name, undef_hex
        ));
    }

    // 3. Identity functions — `double name(double %0)` returning %0 as-is.
    for name in identity_func_symbols {
        ll.push_str(&format!(
            "define double @{}(double %0) {{\n  ret double %0\n}}\n\n",
            name
        ));
    }

    // 4. Closure-wrapper stubs — the JS body ABI of the wrappers
    //    cross-module function-VALUE references name: `double name(i64
    //    callee, i64 this, double a0, double a1, double a2, double a3,
    //    double a4)`. Return NaN-boxed TAG_UNDEFINED. The stub reads no
    //    argument, so its declared width is informational; it matches the
    //    no-op variable/class wrappers in `codegen/export_value_wrappers.rs`.
    //
    //    Used by the failed-module stub block at
    //    `crates/perry/src/commands/compile.rs:~5518` so consumers that
    //    reference `__perry_wrap_perry_fn_<src>__<name>` for a module
    //    whose codegen failed under `--allow-unimplemented` still link.
    //    Without this the link error pre-#903 was masked by the
    //    same-file-default-import collision pointing the consumer at
    //    a SIBLING module's wrapper (e.g. uuid v5.js's `import sha1
    //    from './sha1.js'` plus `import v35 from './v35.js'` both
    //    resolved to v35.js's wrapper); post-#903 the collision is
    //    gone and the missing wrapper surfaces as an undefined symbol.
    //    Refs #903 / uuid `__perry_wrap_perry_fn_...sha1_js__default`.
    for name in wrapper_func_symbols {
        ll.push_str(&format!(
            "define double @{}(i64 %0, i64 %1, double %2, double %3, double %4, double %5, double %6) {{\n  ret double {}\n}}\n\n",
            name, undef_hex
        ));
    }

    // If absolutely nothing was requested, emit a single dummy symbol so
    // the resulting object isn't empty (some linkers complain about empty
    // objects).
    if missing_data_symbols.is_empty()
        && missing_func_symbols.is_empty()
        && identity_func_symbols.is_empty()
        && wrapper_func_symbols.is_empty()
    {
        ll.push_str("@__perry_stubs_placeholder = global i64 0, align 8\n");
    }

    // Resolve the target triple via the same map the rest of the LLVM
    // backend uses, so a Perry short name like "macos" / "ios" turns into
    // the right LLVM triple for clang's `-target` flag.
    let triple = target.and_then(crate::resolve_target_triple);

    compile_ll_to_object(&ll, triple.as_deref())
}

/// Whether an object for `triple` (`None` = the host) is ELF, where the
/// startup-registration unit must use `.init_array`.
fn elf_object(triple: Option<&str>) -> bool {
    match triple {
        Some(t) => {
            t.contains("linux")
                || t.contains("android")
                || t.contains("freebsd")
                || t.contains("netbsd")
                || t.contains("openbsd")
        }
        None => cfg!(all(unix, not(target_vendor = "apple"))),
    }
}

/// IR that runs `func` (an internal `void()`) before `main`.
///
/// On ELF this is a pointer in `.init_array`, not `@llvm.global_ctors`: the
/// in-process TargetMachine is built with `UseInitArray=false` (it must match
/// the native-roots object layout), so LLVM lowers `global_ctors` to the legacy
/// `.ctors` section, which glibc on aarch64 (and any `DT_INIT_ARRAY`-only
/// startup) never runs. The registration then silently never happened: no
/// feature installers, no static shape seed. The pointer is `global`, not
/// `constant`, so the section gets the writable flags the linker expects for
/// `.init_array`, and `@llvm.used` keeps it through `--gc-sections`. Mach-O
/// (`__mod_init_func`) and COFF keep `global_ctors`.
fn startup_registration_ll(func: &str, triple: Option<&str>) -> String {
    if elf_object(triple) {
        format!(
            "@{func}_init_ptr = internal global ptr @{func}, section \".init_array\", align 8\n\
             @llvm.used = appending global [1 x ptr] [ptr @{func}_init_ptr], section \"llvm.metadata\"\n"
        )
    } else {
        format!(
            "@llvm.global_ctors = appending global [1 x {{ i32, ptr, ptr }}] \
             [{{ i32, ptr, ptr }} {{ i32 65535, ptr @{func}, ptr null }}]\n"
        )
    }
}

/// Generate the object that tells the runtime (and perry-stdlib, when linked)
/// which optional features this program installs.
///
/// For each half it defines an internal installer calling that half's install
/// entry points (`js_runtime_install_*` / `js_stdlib_install_*`, all
/// `void()`), and one static constructor that registers them through
/// `js_runtime_register_feature_installer` / `js_stdlib_register_feature_installer`
/// — atomic stores, safe before `main`. The runtime runs its installer at the
/// end of `js_gc_init`; `js_stdlib_init_dispatch` runs the stdlib one, on
/// whichever path initializes the stdlib (the entry prologue, or the lazy
/// `ensure_pump_registered` path of a program codegen did not mark as needing
/// the stdlib). Naming only the program's features is what lets the linker
/// drop every other optional subsystem from the prebuilt full-feature archives;
/// see perry-runtime `feature_hooks` and perry-stdlib `common::feature_hooks`.
///
/// `registrations` are `void()` functions of linked archives the constructor
/// calls first, before `main` (they may only store pointers): an optional
/// archive the runtime never names, such as `perry-wasm-host`, registers its
/// entry points with the runtime this way (`perry_wasm_host_register`).
pub fn generate_feature_installer_object(
    runtime_installs: &[String],
    stdlib_installs: Option<&[String]>,
    registrations: &[String],
    target: Option<&str>,
) -> Result<Vec<u8>> {
    let mut ll = String::new();
    ll.push_str("; Perry feature installer — generated by perry-codegen::stubs\n\n");
    let mut halves = vec![("runtime", runtime_installs)];
    if let Some(stdlib) = stdlib_installs {
        halves.push(("stdlib", stdlib));
    }
    let mut ctor = String::from("define internal void @perry_register_feature_installers() {\n");
    for symbol in registrations {
        ll.push_str(&format!("declare void @{}()\n", symbol));
        ctor.push_str(&format!("  call void @{}()\n", symbol));
    }
    for (half, symbols) in &halves {
        ll.push_str(&format!(
            "declare void @js_{half}_register_feature_installer(ptr)\n"
        ));
        for symbol in symbols.iter() {
            ll.push_str(&format!("declare void @{}()\n", symbol));
        }
        ll.push_str(&format!(
            "\ndefine internal void @perry_{half}_feature_installer() {{\n"
        ));
        for symbol in symbols.iter() {
            ll.push_str(&format!("  call void @{}()\n", symbol));
        }
        ll.push_str("  ret void\n}\n\n");
        ctor.push_str(&format!(
            "  call void @js_{half}_register_feature_installer(ptr @perry_{half}_feature_installer)\n"
        ));
    }
    ctor.push_str("  ret void\n}\n\n");
    ll.push_str(&ctor);
    let triple = target.and_then(crate::resolve_target_triple);
    ll.push_str(&startup_registration_ll(
        "perry_register_feature_installers",
        triple.as_deref(),
    ));
    compile_ll_to_object(&ll, triple.as_deref())
}

/// The LLVM IR of the program's static shape seed unit (design step 4, WRT
/// step 2): the program's literal seeds as data. For each seed: its layout
/// request, its packed key names, and, on targets whose atoms are image
/// data, its keys as atoms and its canonical key list as a cell of the realm
/// image, so the runtime links the list into each agent's key-list trie and
/// publishes the record without allocating (`js_shape_run_static_seed`).
/// The table `@perry_static_seeds` is what the entry's layout image names.
pub fn static_shape_seed_ll(seeds: &[(u32, crate::BirthShape)]) -> String {
    static_shape_seed_ll_impl(seeds, true, None)
}

/// The caller supplies only permanent-image final facts or ordinary births.
/// Body-aware seeds create records; they do not stamp incomplete objects.
fn static_shape_seed_ll_impl(
    seeds: &[(u32, crate::BirthShape)],
    allow_constfn: bool,
    triple: Option<&str>,
) -> String {
    let plan = crate::ProgramLayoutOrdinals::assign(
        crate::layout_ordinals::native_inputs(),
        seeds
            .iter()
            .map(|(id, shape)| crate::layout_ordinals::identity_input(shape, *id)),
    )
    .expect("standalone seed plan");
    static_shape_seed_ll_with_plan(seeds, &plan, allow_constfn, triple, "executable", None)
}

/// `%PerryStaticSeedV1` (perry-abi): rep, request, packed names, keys, list,
/// ConstFn entries, packed length, key count, live bound, entry count.
const SEED_TY: &str = "{ i64, ptr, ptr, ptr, ptr, ptr, i32, i32, i32, i32 }";

pub fn static_shape_seed_ll_with_plan(
    seeds: &[(u32, crate::BirthShape)],
    plan: &crate::ProgramLayoutOrdinals,
    allow_constfn: bool,
    triple: Option<&str>,
    output_type: &str,
    layouts: Option<&crate::layout_families::ProgramLayouts>,
) -> String {
    assert!(
        allow_constfn || seeds.iter().all(|(_, shape)| shape.constfn.is_empty()),
        "ConstFn static seeds require a body-aware runtime seed ABI"
    );
    let triple = triple
        .map(str::to_string)
        .unwrap_or_else(crate::codegen::default_target_triple);
    let mut llmod = LlModule::new(triple.as_str());
    // Image keys need atoms, which only executables carry.
    let image_keys = crate::layout_desc::layouts_enabled(output_type, &triple);
    if let Some(layouts) = layouts {
        crate::layout_desc::set_colours(layouts);
    }
    let mut strings = crate::strings::StringPool::new();
    let mut atoms: std::collections::BTreeMap<String, String> = Default::default();
    let mut records: std::collections::BTreeSet<String> = Default::default();
    // The seed unit is a separate LLVM module from each defining body.
    // Opaque pointers still require every referenced global to be declared
    // here; the defining module emits the one hidden, linkable info constant.
    let body_symbols = seeds
        .iter()
        .flat_map(|(_, shape)| shape.constfn.iter().map(|body| body.symbol.as_str()))
        .collect::<std::collections::BTreeSet<_>>();
    for symbol in body_symbols {
        llmod.add_raw_global(format!(
            "@{symbol} = external constant {}",
            crate::fn_info::INFO_TYPE
        ));
    }
    let mut rows = Vec::new();
    let mut fixups = Vec::new();
    for (i, (id, shape)) in seeds.iter().enumerate() {
        let word = plan
            .identity_word(*id)
            .expect("seed identity in image plan");
        let request = crate::layout_ordinals::request_symbol(*id);
        llmod.add_raw_global(format!(
            "@{request} = weak_odr global {{ i32, i32 }} {{ i32 {id}, i32 {word} }}, align 4"
        ));
        let bytes: String = shape.keys.iter().map(|b| format!("\\{b:02X}")).collect();
        llmod.add_raw_global(format!(
            "@perry_static_seed_keys_{i} = private unnamed_addr constant [{} x i8] c\"{bytes}\"",
            shape.keys.len()
        ));
        let constfn = if shape.constfn.is_empty() {
            "ptr null".to_string()
        } else {
            let mut prior = None;
            let mut mask = 0u32;
            let entries = shape
                .constfn
                .iter()
                .map(|body| {
                    assert!(
                        body.slot < 32 && prior.is_none_or(|slot| body.slot > slot),
                        "ConstFn seed entries must be sorted and unique"
                    );
                    assert!(
                        body.symbol
                            .bytes()
                            .all(|b| b.is_ascii_alphanumeric() || b"_.$".contains(&b)),
                        "invalid ConstFn body info symbol"
                    );
                    prior = Some(body.slot);
                    mask |= 1 << body.slot;
                    format!(
                        "{{ i32, ptr }} {{ i32 {}, ptr @{} }}",
                        body.slot, body.symbol
                    )
                })
                .collect::<Vec<_>>()
                .join(", ");
            let special = (0..32)
                .filter(|slot| (shape.rep >> (2 * slot)) & 3 == 3)
                .fold(0u32, |mask, slot| mask | (1 << slot));
            assert_eq!(mask, special, "ConstFn seed rep/body mismatch");
            llmod.add_raw_global(format!(
                "@perry_static_seed_constfn_{i} = private constant [{} x {{ i32, ptr }}] [{entries}]",
                shape.constfn.len()
            ));
            format!("ptr @perry_static_seed_constfn_{i}")
        };
        // The key list as image data: every key an atom, the cell its
        // strings in key order. A key the pool cannot image (empty, WTF-8)
        // leaves the seed to the by-names mint.
        let mut image = None;
        if image_keys {
            let names: Vec<&[u8]> = shape
                .keys
                .split(|b| *b == 0)
                .filter(|name| !name.is_empty())
                .collect();
            let mut atom_items = Vec::new();
            let mut key_records = Vec::new();
            for (slot, name) in names.iter().enumerate() {
                let Ok(name) = std::str::from_utf8(name) else {
                    break;
                };
                let Some(atom) =
                    crate::layout_desc::atom(&mut llmod, &mut strings, &mut atoms, name)
                else {
                    break;
                };
                let idx = strings.intern(name);
                let entry = strings.entry(idx);
                let record = crate::codegen::image_record_symbol(entry);
                if records.insert(record.clone()) {
                    crate::codegen::emit_image_record(&mut llmod, entry);
                }
                atom_items.push(format!(
                    "{} {{ ptr @{atom}, i32 {slot}, i8 0, [3 x i8] zeroinitializer }}",
                    crate::layout_desc::KEY_TY
                ));
                key_records.push(record);
            }
            if names.len() == shape.key_count as usize && atom_items.len() == names.len() {
                let list = format!("perry_static_seed_list_{i}");
                fixups.extend(crate::codegen::realm_image::emit_key_list_cell(
                    &mut llmod,
                    &list,
                    &key_records,
                ));
                llmod.add_raw_global(format!(
                    "@perry_static_seed_atoms_{i} = private unnamed_addr constant [{} x {}] [{}], align 8",
                    atom_items.len(),
                    crate::layout_desc::KEY_TY,
                    atom_items.join(", ")
                ));
                image = Some(format!(
                    "ptr @perry_static_seed_atoms_{i}, ptr getelementptr (i8, ptr @{list}, i64 {})",
                    crate::target_layout::GC_HEADER_SIZE_BYTES
                ));
            }
        }
        rows.push(format!(
            "{SEED_TY} {{ i64 {}, ptr @{request}, ptr @perry_static_seed_keys_{i}, {}, {constfn}, i32 {}, i32 {}, i32 {}, i32 {} }}",
            shape.rep as i64,
            image.unwrap_or_else(|| "ptr null, ptr null".to_string()),
            shape.keys.len(),
            shape.key_count,
            shape.live,
            shape.constfn.len()
        ));
    }
    llmod.add_raw_global(format!(
        "@perry_static_seeds = constant {{ i32, i32, [{n} x {SEED_TY}] }} {{ i32 {n}, i32 0, [{n} x {SEED_TY}] [{}] }}, align 8",
        rows.join(", "),
        n = rows.len()
    ));
    let mut ll = String::new();
    ll.push_str("; Perry static shape seeds — generated by perry-codegen::stubs\n\n");
    if !fixups.is_empty() {
        // 64-bit Apple targets: tag the cells' string slots before `main`.
        let func = llmod.define_function("perry_static_seed_tags", VOID, vec![]);
        let _ = func.create_block("entry");
        let blk = func.block_mut(0).unwrap();
        crate::codegen::realm_image::emit_tag_fixups(blk, &fixups);
        blk.ret_void();
        ll.push_str(&llmod.to_ir());
        ll.push_str(&startup_registration_ll(
            "perry_static_seed_tags",
            Some(triple.as_str()),
        ));
    } else {
        ll.push_str(&llmod.to_ir());
    }
    ll
}

/// Compile [`static_shape_seed_ll`] to an object for the link.
pub fn generate_static_shape_seed_object(
    seeds: &[(u32, crate::BirthShape)],
    target: Option<&str>,
) -> Result<Vec<u8>> {
    let triple = target.and_then(crate::resolve_target_triple);
    compile_ll_to_object(
        &static_shape_seed_ll_impl(seeds, true, triple.as_deref()),
        triple.as_deref(),
    )
}

/// Driver entry: the seed unit consumes the exact plan shared by every package.
pub fn generate_static_shape_seed_object_with_plan(
    seeds: &[(u32, crate::BirthShape)],
    plan: &crate::ProgramLayoutOrdinals,
    target: Option<&str>,
    output_type: &str,
    layouts: &crate::layout_families::ProgramLayouts,
) -> Result<Vec<u8>> {
    let triple = target.and_then(crate::resolve_target_triple);
    compile_ll_to_object(
        &static_shape_seed_ll_with_plan(
            seeds,
            plan,
            true,
            triple.as_deref(),
            output_type,
            Some(layouts),
        ),
        triple.as_deref(),
    )
}

