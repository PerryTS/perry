// ─── Circular reference detection ────────────────────────────────────────────
thread_local! {
    /// Stack of object pointers currently being stringified (for circular detection).
    pub(crate) static STRINGIFY_STACK: RefCell<Vec<usize>> = const { RefCell::new(Vec::new()) };

    /// Reusable scratch buffer for JSON.stringify (issue #64). Avoids the
    /// per-call `String::with_capacity` allocate+free that dominated the
    /// small-stringify path. Wrapped in `Cell<Option<_>>` so reentrant calls
    /// (via `toJSON` callbacks etc.) get a fresh buffer instead of panicking
    /// on a `RefCell` borrow conflict; the larger of the two is restored.
    pub(crate) static STRINGIFY_BUF: std::cell::Cell<Option<String>> =
        std::cell::Cell::new(Some(String::with_capacity(4096)));

    /// Per-call shape-template cache (#64 follow-up), as a STACK of frames.
    /// Each template is keyed on its `keys_array` raw pointer, which is a
    /// **GC-managed `ArrayHeader*`** — so `scan_parse_roots_mut` visits every
    /// frame's every key as a real (marking AND rewriting) root.
    ///
    /// ★ #7268: this comment used to assert the invariant that made the raw
    /// key safe —
    ///
    /// > within one top-level stringify call no GC runs over the user object
    /// > graph (the buffer/result allocations don't move keys arrays), so
    /// > pointer identity is a stable shape ID
    ///
    /// — and `toJSON` falsifies it. A `toJSON` is user JS: it allocates, it
    /// can reach a safepoint, and the minor there is evacuating. A stale key
    /// then either misses (merely slow) or, worse, **collides with a
    /// newly-allocated array at the recycled address and matches the wrong
    /// shape**; and `set_to_json_key_for_template_field` reads the property
    /// NAME strings out of `keys_arr`, i.e. dereferences retired from-space.
    ///
    /// ★ Why a stack rather than a moved-out `Vec`. Reentrancy used to be
    /// handled by `take_shape_cache()` moving the whole cache into a Rust
    /// local for the duration of the inner call. While it sat there the root
    /// scanner could not see it, so the inner call — the `toJSON`, i.e.
    /// precisely the code that moves things — left every saved key stale, and
    /// the outer call resumed using them. Keeping the frames in the TLS is
    /// what makes the scanner's coverage complete; `take`/`restore` now push
    /// and pop a frame instead of moving the storage out of the collector's
    /// reach.
    ///
    /// Frame 0 always exists (the top-level call's), so the emit path never
    /// has to check for an empty stack.
    ///
    /// `Box<ShapeTemplate>` lives on the heap so its address is stable
    /// even when a frame `Vec` reallocates — we hand out raw pointers
    /// to the templates and they must outlive the borrow.
    pub(crate) static SHAPE_CACHE: RefCell<Vec<Vec<Box<ShapeTemplate>>>> =
        RefCell::new(vec![Vec::new()]);

    /// Key string intern cache for JSON.parse (issue #51 follow-up).
    /// Maps key bytes → already-allocated StringHeader pointer.
    /// Avoids re-allocating "id", "name", etc. for every record in a
    /// homogeneous JSON array. Cleared at the end of each top-level parse.
    /// `pub(crate)` so `json_tape`'s materializer can share the cache —
    /// without this, each tape-path force-materialize re-allocates every
    /// key and burns 3× the time + RSS vs the direct parser.
    pub(crate) static PARSE_KEY_CACHE: RefCell<std::collections::HashMap<Vec<u8>, *const StringHeader>> =
        RefCell::new(std::collections::HashMap::new());
    /// Tiny hot-key mirror for homogeneous object parses. Most API JSON
    /// repeats the same handful of property names thousands of times; a
    /// short linear probe avoids hashing + HashMap probing on the steady
    /// state while PARSE_KEY_CACHE remains the owning/rooting store.
    static PARSE_KEY_RING: RefCell<Vec<*const StringHeader>> = const { RefCell::new(Vec::new()) };

    /// Shared keys_array cache for direct JSON.parse objects.
    ///
    /// The generic object setter builds a shape one property at a time. For
    /// homogeneous JSON records that means every parsed object participates in
    /// the transition-cache machinery before field values are written. The tape
    /// path avoids that churn by materializing from a compact token stream; the
    /// direct parser needs the same shape sharing so `PERRY_JSON_TAPE=0` does
    /// not manufacture short-lived keys arrays and forwarding stubs in old
    /// pages.
    pub(crate) static PARSE_SHAPE_CACHE: RefCell<Vec<ParseShapeCacheEntry>> =
        const { RefCell::new(Vec::new()) };

    /// Reentrancy depth counter for JSON.stringify (issue #67). 0 means
    /// no call in progress; ≥1 means a reentrant (toJSON callback) path.
    /// Used to skip the shape_cache save/restore dance for the common
    /// non-reentrant case — a plain `clear_shape_cache` at the outermost
    /// call's exit handles correctness without a Vec alloc/swap.
    pub(crate) static STRINGIFY_DEPTH: std::cell::Cell<u32> = const { std::cell::Cell::new(0) };

    /// One-shot guard so `toJSON` is applied at most once per value (#321 /
    /// ECMA-262 §25.5.2.2). `SerializeJSONProperty` calls `value.toJSON(key)`
    /// once and then serializes the RESULT as an ordinary object/array —
    /// without re-invoking `toJSON` on that result. Without this, a `toJSON`
    /// that returns another object whose prototype/own chain also has a
    /// `toJSON` (e.g. `{ toJSON() { return new ClassWithToJSON(); } }`) would
    /// re-apply the inner `toJSON` and diverge from Node. We set this flag
    /// right before serializing an OBJECT-typed `toJSON` result; the very next
    /// `object_get_to_json` consumes (clears) it and returns `None`, so the
    /// result object emits its own fields while its children recurse normally.
    pub(crate) static SUPPRESS_NEXT_TO_JSON: std::cell::Cell<bool> =
        const { std::cell::Cell::new(false) };

    /// The property key handed to `toJSON` for the value currently being
    /// serialized (#5909 — test262 JSON/stringify/value-tojson-arguments).
    /// ECMA-262 §25.5.2.2 SerializeJSONProperty step 2.b.i is
    /// `Call(toJSON, value, « key »)`, where `key` is the empty String at the
    /// root, an object's own property name for a member, and the stringified
    /// index for an array element. Set right before recursing into each child
    /// and read by `object_get_to_json` / `array_get_to_json` /
    /// `bigint_apply_to_json`. Held as an owned Rust `String` (not a JS heap
    /// pointer) so it never roots a movable GC allocation across the string
    /// allocation the probes perform, and reset at every top-level stringify
    /// entry so a key from one call can't leak into the next.
    pub(crate) static TO_JSON_KEY: std::cell::RefCell<String> =
        const { std::cell::RefCell::new(String::new()) };

    /// Cached verdict on whether the default `Object.prototype` carries a
    /// `toJSON` property (#6009). One of `PROTO_TOJSON_DIRTY` /
    /// `PROTO_TOJSON_ABSENT` / `PROTO_TOJSON_PRESENT`. Computed lazily by the
    /// first `object_get_to_json` fast-path probe of a stringify call and
    /// invalidated at every top-level stringify entry and after every user
    /// callback (`toJSON` / replacer) — the only points where user code could
    /// have added `Object.prototype.toJSON` since the last computation.
    pub(crate) static OBJECT_PROTO_TOJSON_STATE: std::cell::Cell<u8> =
        const { std::cell::Cell::new(0) };

    /// One-time-resolved NaN-box bits of the default `Object.prototype`
    /// object (0 = not yet resolved). Resolving it live per stringify call
    /// (`default_object_prototype_bits`: globalThis generic getter + key
    /// alloc + closure prop lookup) dominated the post-#6009 fast-path
    /// profile. Per spec the `Object.prototype` property is non-writable /
    /// non-configurable, so the resolution itself can never change — only
    /// the OBJECT can move under an evacuating GC, which is why this slot is
    /// registered as a GC mutable root
    /// (`scan_json_object_proto_cache_root_mut`): marking visits it and
    /// evacuation rewrites it.
    pub(crate) static CACHED_OBJECT_PROTO_BITS: std::cell::Cell<u64> =
        const { std::cell::Cell::new(0) };

    /// GC roots for in-progress JSON.parse. Each entry is a JSValue bit pattern
    /// (stored as f64 so the scanner can hand it to the NaN-boxed mark path).
    ///
    /// Why this exists (issue #46): parse_array/parse_object build their result
    /// incrementally over thousands of iterations. Mid-parse heap allocations
    /// (`js_string_from_bytes` → gc_malloc → adaptive count trigger, or an arena
    /// block overflow) run GC while the in-progress array/object lives only on
    /// the Rust call stack. The conservative stack scan only captures callee-
    /// saved registers via setjmp; values held in caller-saved regs (or on
    /// the Rust-heap backing of `Vec<(Vec<u8>, JSValue)>` inside parse_object)
    /// are invisible and get swept. Symptom was `JSON.parse(big_array)` silently
    /// truncating at ~1666 records (= when the second adaptive malloc GC fires).
    pub(crate) static PARSE_ROOTS: RefCell<Vec<f64>> = const { RefCell::new(Vec::new()) };
}

pub(crate) struct ParseShapeCacheEntry {
    pub(crate) keys: Vec<*const StringHeader>,
    pub(crate) keys_array: *mut crate::ArrayHeader,
}

pub(crate) const PARSE_SHAPE_CACHE_CAP: usize = 256;

// ─── Shared file-local NaN-box tag / type-hint constants ─────────────────────

pub(crate) const TAG_UNDEFINED: u64 = 0x7FFC_0000_0000_0001;
pub(crate) const TAG_NULL: u64 = 0x7FFC_0000_0000_0002;
pub(crate) const TAG_FALSE: u64 = 0x7FFC_0000_0000_0003;
pub(crate) const TAG_TRUE: u64 = 0x7FFC_0000_0000_0004;
pub(crate) const POINTER_TAG: u64 = 0x7FFD_0000_0000_0000;
pub(crate) const STRING_TAG: u64 = 0x7FFF_0000_0000_0000;
pub(crate) const BIGINT_TAG: u64 = 0x7FFA_0000_0000_0000;
pub(crate) const INT32_TAG: u64 = 0x7FFE_0000_0000_0000;
pub(crate) const POINTER_MASK: u64 = 0x0000_FFFF_FFFF_FFFF;
pub(crate) const INT32_MASK: u64 = 0x0000_0000_FFFF_FFFF;

pub(crate) const TYPE_UNKNOWN: u32 = 0;
pub(crate) const TYPE_OBJECT: u32 = 1;
pub(crate) const TYPE_ARRAY: u32 = 2;

/// Maximum cache entries per call. Workloads with more distinct shapes
/// fall back to per-object building. We never evict — the raw pointers we
/// hand out must outlive cache mutations, and `swap_remove` would drop a
/// `Box` whose heap address might be in active use up the call stack.
/// 32 entries × ~40 bytes ≈ 1.3 KB; a stringify graph that exceeds this
/// gets the pre-cache slow path on overflow shapes only.
pub(crate) const SHAPE_CACHE_CAP: usize = 32;

/// Stringify depth counter — avoids TLS `STRINGIFY_STACK` access for
/// shallow (non-circular) object graphs. Only activates full tracking
/// at depth > MAX_FAST_DEPTH to catch genuine circular refs.
pub(crate) const MAX_FAST_DEPTH: u32 = 128;

// ─── Parse-roots helpers ─────────────────────────────────────────────────────

#[inline]
pub(crate) fn parse_root_push(v: JSValue) -> usize {
    PARSE_ROOTS.with(|r| {
        let mut r = r.borrow_mut();
        let idx = r.len();
        r.push(f64::from_bits(v.bits()));
        idx
    })
}

#[inline]
pub(crate) fn parse_root_set(idx: usize, v: JSValue) {
    PARSE_ROOTS.with(|r| {
        if let Some(slot) = r.borrow_mut().get_mut(idx) {
            *slot = f64::from_bits(v.bits());
        }
    });
}

#[inline]
pub(crate) fn parse_root_get(idx: usize) -> JSValue {
    PARSE_ROOTS.with(|r| {
        r.borrow()
            .get(idx)
            .map(|slot| JSValue::from_bits(slot.to_bits()))
            .unwrap_or_else(JSValue::undefined)
    })
}

#[inline]
pub(crate) fn parse_root_object_ptr(idx: usize) -> *mut crate::ObjectHeader {
    (parse_root_get(idx).bits() & POINTER_MASK) as *mut crate::ObjectHeader
}

#[inline]
pub(crate) fn parse_root_array_ptr(idx: usize) -> *mut crate::ArrayHeader {
    (parse_root_get(idx).bits() & POINTER_MASK) as *mut crate::ArrayHeader
}

#[inline]
pub(crate) fn parse_root_save_len() -> usize {
    PARSE_ROOTS.with(|r| r.borrow().len())
}

#[inline]
pub(crate) fn parse_root_restore(len: usize) {
    PARSE_ROOTS.with(|r| r.borrow_mut().truncate(len));
}

#[inline]
pub(crate) fn cached_parse_key_ptr(key_bytes: &[u8]) -> *const StringHeader {
    let ring_hit = PARSE_KEY_RING.with(|ring| {
        for &ptr in ring.borrow().iter() {
            if ptr.is_null() {
                continue;
            }
            unsafe {
                let len = (*ptr).byte_len as usize;
                if len != key_bytes.len() {
                    continue;
                }
                let data = (ptr as *const u8).add(std::mem::size_of::<StringHeader>());
                if std::slice::from_raw_parts(data, len) == key_bytes {
                    return Some(ptr);
                }
            }
        }
        None
    });
    if let Some(ptr) = ring_hit {
        return ptr;
    }

    let cached = PARSE_KEY_CACHE.with(|c| c.borrow().get(key_bytes).copied());
    if let Some(ptr) = cached {
        remember_parse_key_ring(ptr);
        return ptr;
    }

    // Issue #179: allocate cached key strings in the longlived arena. They
    // are rooted by `scan_parse_roots_mut` and reused across repeated parses
    // of homogeneous JSON records.
    let ptr =
        crate::string::js_string_from_bytes_longlived(key_bytes.as_ptr(), key_bytes.len() as u32);
    PARSE_KEY_CACHE.with(|c| {
        c.borrow_mut().insert(key_bytes.to_vec(), ptr);
    });
    remember_parse_key_ring(ptr);
    ptr
}

#[inline]
fn remember_parse_key_ring(ptr: *const StringHeader) {
    PARSE_KEY_RING.with(|ring| {
        let mut ring = ring.borrow_mut();
        if ring.contains(&ptr) {
            return;
        }
        if ring.len() == 16 {
            ring.remove(0);
        }
        ring.push(ptr);
    });
}

pub(crate) fn clear_parse_key_ring() {
    PARSE_KEY_RING.with(|ring| ring.borrow_mut().clear());
}

#[inline]
pub(crate) unsafe fn parse_shape_keys_array(
    keys: &[*const StringHeader],
) -> *mut crate::ArrayHeader {
    PARSE_SHAPE_CACHE.with(|cache| {
        {
            let cache = cache.borrow();
            for entry in cache.iter().rev() {
                if entry.keys.len() == keys.len()
                    && entry
                        .keys
                        .iter()
                        .zip(keys.iter())
                        .all(|(a, b)| std::ptr::eq(*a, *b))
                {
                    return entry.keys_array;
                }
            }
        }

        let arr = crate::array::js_array_alloc_with_length_longlived(keys.len() as u32);
        let elements_ptr =
            (arr as *mut u8).add(std::mem::size_of::<crate::ArrayHeader>()) as *mut f64;
        for (i, &key_ptr) in keys.iter().enumerate() {
            let bits = crate::value::STRING_TAG | (key_ptr as u64 & crate::value::POINTER_MASK);
            // GC_STORE_AUDIT(INIT): parse shape keys array is filled before cache publication.
            *elements_ptr.add(i) = f64::from_bits(bits);
            crate::array::note_array_slot_layout_only(arr, i, bits);
        }
        let header = (arr as *mut u8).sub(crate::gc::GC_HEADER_SIZE) as *mut crate::gc::GcHeader;
        (*header).gc_flags |= crate::gc::GC_FLAG_SHAPE_SHARED;

        let mut cache = cache.borrow_mut();
        if cache.len() < PARSE_SHAPE_CACHE_CAP {
            cache.push(ParseShapeCacheEntry {
                keys: keys.to_vec(),
                keys_array: arr,
            });
        }
        arr
    })
}

// ─── Stringify scratch / shape-cache lifecycle ───────────────────────────────

/// Take the shared scratch buffer (or allocate a fresh one on reentrancy).
#[inline]
pub(crate) fn take_stringify_buf() -> String {
    STRINGIFY_BUF.with(|b| b.take()).unwrap_or_default()
}

/// Restore the scratch buffer after use. In a reentrant call the inner
/// restore runs first with a (typically smaller) buffer, but the outer
/// restore runs last and overwrites with its larger buffer — so the
/// final TLS state always holds the largest recently-used buffer without
/// needing a per-call capacity comparison.
#[inline]
pub(crate) fn restore_stringify_buf(mut buf: String) {
    buf.clear();
    STRINGIFY_BUF.with(|b| b.set(Some(buf)));
}

#[inline]
pub(crate) fn json_string_from_output_bytes(bytes: &[u8]) -> *mut StringHeader {
    if bytes.is_ascii() {
        js_string_from_ascii_bytes(bytes.as_ptr(), bytes.len() as u32)
    } else {
        js_string_from_bytes(bytes.as_ptr(), bytes.len() as u32)
    }
}

/// Receipt for a pushed shape-cache frame. Consumed by `restore_shape_cache`.
///
/// It is not `Copy` and carries a `Drop` that pops the frame, so a JS exception
/// unwinding past the matching `restore_shape_cache` cannot leave the stack one
/// frame deep forever. (`clear_shape_cache` truncates to frame 0 as a second
/// line of defence, for the `longjmp`-style exits that skip `Drop` entirely.)
pub(crate) struct SavedShapeCache {
    restored: bool,
}

impl Drop for SavedShapeCache {
    fn drop(&mut self) {
        if !self.restored {
            SHAPE_CACHE.with(|c| {
                let mut stack = c.borrow_mut();
                if stack.len() > 1 {
                    stack.pop();
                }
            });
        }
    }
}

/// Push a fresh shape-cache frame for the duration of a nested stringify call.
/// A reentrant `toJSON` callback would otherwise inherit the outer call's
/// templates and (worse) clear them on exit, dangling pointers we already
/// handed out. Mirrors `take_stringify_buf` in spirit.
///
/// #7268: this used to `mem::take` the cache into a Rust local. The storage
/// then sat outside the TLS — and therefore outside `scan_parse_roots_mut`'s
/// reach — for the whole of the inner call, which is the call that runs user
/// `toJSON` code and moves things. Pushing a frame keeps every saved key
/// visible to the collector.
#[inline]
pub(crate) fn take_shape_cache() -> SavedShapeCache {
    SHAPE_CACHE.with(|c| c.borrow_mut().push(Vec::new()));
    SavedShapeCache { restored: false }
}

#[inline]
pub(crate) fn restore_shape_cache(mut saved: SavedShapeCache) {
    saved.restored = true;
    SHAPE_CACHE.with(|c| {
        let mut stack = c.borrow_mut();
        if stack.len() > 1 {
            stack.pop();
        }
    });
}

/// Clear the cache without allocating a fresh Vec (keeps capacity, drops
/// entries). Used in place of restore when we know the cache was empty at call
/// entry — the outermost stringify call in a tight loop skips the save
/// entirely.
///
/// It also truncates the frame stack back to one, which is what re-establishes
/// the invariant after a JS exception unwound past a `restore_shape_cache`.
#[inline]
pub(crate) fn clear_shape_cache() {
    SHAPE_CACHE.with(|c| {
        let mut stack = c.borrow_mut();
        stack.truncate(1);
        stack[0].clear();
    });
}

/// The live shape-cache frame — the innermost stringify call's.
#[inline]
pub(crate) fn with_shape_cache_frame<R>(f: impl FnOnce(&mut Vec<Box<ShapeTemplate>>) -> R) -> R {
    SHAPE_CACHE.with(|c| {
        let mut stack = c.borrow_mut();
        let frame = stack.last_mut().expect("shape cache always has frame 0");
        f(frame)
    })
}

#[inline]
pub(crate) fn make_pointer_bits(ptr: *const u8) -> u64 {
    POINTER_TAG | (ptr as u64 & POINTER_MASK)
}

// ─── GC root scanners ────────────────────────────────────────────────────────

/// Root scanner called by GC — marks every value in PARSE_ROOTS as live.
pub fn scan_parse_roots(mark: &mut dyn FnMut(f64)) {
    let mut visitor = crate::gc::RuntimeRootVisitor::for_copy(mark);
    scan_parse_roots_mut(&mut visitor);
}

pub fn scan_parse_roots_mut(visitor: &mut crate::gc::RuntimeRootVisitor<'_>) {
    PARSE_ROOTS.with(|r| {
        for v in r.borrow_mut().iter_mut() {
            visitor.visit_nanbox_f64_slot(v);
        }
    });
    // Also mark interned key strings so GC doesn't sweep them mid-parse.
    PARSE_KEY_CACHE.with(|c| {
        for ptr in c.borrow_mut().values_mut() {
            visitor.visit_tagged_raw_const_ptr_slot(ptr, crate::value::STRING_TAG);
        }
    });
    // PARSE_KEY_RING mirrors the cache's hottest values. It does not own
    // their liveness, but its duplicate addresses must follow an old-page
    // move after PARSE_KEY_CACHE has kept the strings alive.
    PARSE_KEY_RING.with(|ring| {
        for ptr in ring.borrow_mut().iter_mut() {
            let mut addr = *ptr as usize;
            if visitor.visit_metadata_usize_slot(&mut addr) {
                *ptr = addr as *const StringHeader;
            }
        }
    });
    PARSE_SHAPE_CACHE.with(|c| {
        for entry in c.borrow_mut().iter_mut() {
            visitor.visit_raw_mut_ptr_slot(&mut entry.keys_array);
            for key in entry.keys.iter_mut() {
                visitor.visit_tagged_raw_const_ptr_slot(key, crate::value::STRING_TAG);
            }
        }
    });
    // #7268: the STRINGIFY-side shape cache keys every template on a raw
    // `ArrayHeader*` and reads the property-name strings back out of it. Its
    // doc comment used to claim no GC could run over the user object graph
    // during one stringify call; `toJSON` is user JS and falsifies that. Marked
    // AND rewritten, on EVERY frame — the reentrancy save is a pushed frame
    // rather than a moved-out `Vec` precisely so that "every frame" is
    // reachable from here (see `SHAPE_CACHE`).
    SHAPE_CACHE.with(|c| {
        for frame in c.borrow_mut().iter_mut() {
            for template in frame.iter_mut() {
                let mut keys_arr = template.keys_arr.get();
                if keys_arr.is_null() {
                    continue;
                }
                visitor.visit_raw_mut_ptr_slot(&mut keys_arr);
                template.keys_arr.set(keys_arr);
            }
        }
    });
    // #6009: the once-resolved default-`Object.prototype` cache must be
    // rewritten when an evacuating GC moves the prototype object (and marked
    // so the slot can never point at swept memory). Guard against a stale
    // pointer whose backing arena block no longer exists (the unit-test
    // harness resets arenas between tests while thread-locals persist):
    // visiting it would walk freed memory, so drop the cache instead — the
    // next stringify probe simply re-resolves.
    CACHED_OBJECT_PROTO_BITS.with(|c| {
        let mut bits = c.get();
        if bits != 0 {
            let addr = (bits & crate::value::POINTER_MASK) as usize;
            if matches!(
                crate::arena::classify_heap_generation(addr),
                crate::arena::HeapGeneration::Unknown
            ) {
                c.set(0);
            } else {
                visitor.visit_nanbox_u64_slot(&mut bits);
                c.set(bits);
            }
        }
    });
}

