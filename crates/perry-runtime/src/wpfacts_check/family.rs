//! The family claim (check mode, instrumented variant only): the families
//! `family_reach` says the program never creates or observes
//! (`perry_verify_facts_families`, called by a check-mode `main`), and the
//! witnesses of it. A witness that sees a claimed family reports a false
//! proof with verdict `family` and exits 86.
//!
//! - birth: `buffer::store::store_alloc`, the one allocation of every byte
//!   cell (typed arrays, Buffer, ArrayBuffer, SharedArrayBuffer, DataView
//!   backing), whoever asks for it: a value that arrives from a native
//!   module, a file read or a worker message is caught at the same point.
//!   The scratch cells of a comparator sort are no JavaScript values
//!   ([`Scratch`]). `regex::instance::new`, the one birth of every RegExp
//!   object, is the regex engine's.
//! - observation: codegen emits `perry_verify_facts_family_observed` at a
//!   compiled read of a global of a claimed family (a builtin global is an
//!   ordinary cached property read of the global object, so the runtime has
//!   no read by name to test): a family's global, constructor or prototype
//!   observed without any birth is a report too.
//!
//! The witness calls are written at the END of an existing line of their
//! function (`store_alloc`, `sort`, `regex::instance::new`), and this module is
//! declared last in `wpfacts_check.rs`: a line added to those files moves the
//! panic locations of the default build and with them the layout of the one
//! codegen unit the runtime is, so default binaries would stop being
//! byte-identical. The scratch guard is dropped before the comparator runs:
//! what user code allocates there is a value again.
//!
//! None of this is in the default archives: a default binary neither calls
//! `perry_verify_facts_families` nor carries a witness.
use super::report::Witness;
use std::cell::Cell;
use std::sync::atomic::{AtomicI64, AtomicU64, Ordering::Relaxed};

// `FAMILY_IDS`, generated by build.rs from the one family table
// (`perry_runtime_manifest::families`).
include!(concat!(env!("OUT_DIR"), "/family_table.rs"));

static NEVER: AtomicU64 = AtomicU64::new(0);
static SITE: AtomicI64 = AtomicI64::new(0);
static SITE_LEN: AtomicI64 = AtomicI64::new(0);

thread_local! {
    static SCRATCH: Cell<u32> = const { Cell::new(0) };
}

/// The claim of one compiled image: `never` holds a bit per family in table
/// order. With several images a family is claimed only if every image
/// claims it (their installs are a union).
#[no_mangle]
pub extern "C" fn perry_verify_facts_families(never: i64, site: i64, site_len: i64) {
    if SITE.load(Relaxed) == 0 {
        SITE_LEN.store(site_len, Relaxed);
        SITE.store(site, Relaxed);
        NEVER.store(never as u64, Relaxed);
    } else {
        NEVER.fetch_and(never as u64, Relaxed);
    }
}

#[cold]
#[inline(never)]
fn fail(set: u64, what: String) -> ! {
    let family = FAMILY_IDS
        .get(set.trailing_zeros() as usize)
        .copied()
        .unwrap_or("?");
    // The site's metadata carries the verdict and the predicate (`family`).
    Witness::raw(SITE.load(Relaxed), SITE_LEN.load(Relaxed))
        .fail_static(format!("{family}: {what}"))
}

fn family_bit(id: &str) -> u64 {
    FAMILY_IDS
        .iter()
        .position(|f| *f == id)
        .map_or(0, |i| 1 << i)
}

/// A value of family `id` is born.
#[inline]
pub(crate) fn born(id: &str, what: impl FnOnce() -> String) {
    let never = NEVER.load(Relaxed);
    if never == 0 {
        return;
    }
    let bit = family_bit(id);
    if never & bit != 0 {
        fail(bit, what());
    }
}

/// A byte cell of `brand` and `len` elements is born.
#[inline]
pub(crate) fn byte_cell_born(brand: u8, len: u32) {
    if NEVER.load(Relaxed) != 0 && SCRATCH.with(|s| s.get()) == 0 {
        born("typedarray", || {
            format!("a byte cell is born (brand {brand}, length {len})")
        });
    }
}

/// Compiled code reads a global of a family the facts say is never created
/// or observed (the site's metadata names the global and the family).
#[no_mangle]
pub extern "C" fn perry_verify_facts_family_observed(site: i64, site_len: i64) {
    Witness::raw(site, site_len).fail("family", "the global is observed".into())
}

/// While one lives on this thread, a byte cell that is born is a private
/// workspace of the runtime, never handed to JavaScript (the two scratch
/// cells of `array::sort`).
pub(crate) struct Scratch;

impl Scratch {
    pub(crate) fn enter() -> Self {
        SCRATCH.with(|s| s.set(s.get() + 1));
        Scratch
    }
}

impl Drop for Scratch {
    fn drop(&mut self) {
        SCRATCH.with(|s| s.set(s.get() - 1));
    }
}
