//! The runtime side of a `family_reach` "never" (DESIGN-family-reach, the
//! NEVER_MASK contract).
//!
//! The compiler links a runtime family's install (`js_runtime_install_*`)
//! only when the whole-program fact `family_reach` says the program may
//! create or observe a value of that family. For a family the fact says the
//! program never uses, the generated installer does not name the install, so
//! the linker drops the family's code, and it calls
//! [`js_runtime_families_never`] with the family's bit instead: the claim.
//!
//! A claim is checked where a value of the family is born, in every build:
//! [`byte_cell_birth`] is one load and one test in `buffer::store::store_alloc`,
//! the one allocation of every byte cell. A birth under a claim aborts
//! ([`never`]); it never runs on with a value the missing code cannot serve.
//! So does an entry of the family whose slot is empty
//! ([`byte_cells_not_installed`]): the typed-array constructors and the
//! method tower do not fall through to a default value.
//!
//! No claim, no check: a process without a Perry image that claims (a host
//! that links the archive itself, a test, an image compiled with the fact
//! switched off) behaves as before. With several images in one process a
//! family is claimed only if every image claims it, and an install by any of
//! them withdraws the claim for good (their installs are a union,
//! `feature_hooks`).
//!
//! This file is declared last in `lib.rs`, and the calls into it are written
//! on existing lines of their functions: a line added to a runtime source
//! file moves the panic locations after it, and with them the layout of the
//! one codegen unit the runtime is.
use std::sync::atomic::{AtomicU64, Ordering::Relaxed};

// `BYTE_CELLS`: the typed-array family's bit, generated by build.rs from the
// one family table (`perry_runtime_manifest::families`).
include!(concat!(env!("OUT_DIR"), "/family_bits.rs"));

/// The families claimed never by every image and installed by none.
static NEVER: AtomicU64 = AtomicU64::new(0);
/// The families some image installed.
static INSTALLED: AtomicU64 = AtomicU64::new(0);
/// Each registered image's claim, by its installer's registration index. An
/// image that makes none (compiled without the fact) claims nothing.
static IMAGE_NEVER: [AtomicU64; crate::feature_hooks::MAX_IMAGES] =
    [const { AtomicU64::new(0) }; crate::feature_hooks::MAX_IMAGES];

/// The claim of one compiled image: `never` holds a bit per family, in the
/// order of the family table, for the families its facts say the program
/// never creates or observes; `image` is the image's registered installer.
/// Called first by that installer
/// (`perry_codegen::stubs::generate_feature_installer_object`), which
/// `js_gc_init` runs after every image has registered. Idempotent: a thread
/// that initializes later runs the installers again.
#[no_mangle]
pub extern "C" fn js_runtime_families_never(never: i64, image: extern "C" fn()) {
    let images = crate::feature_hooks::registered_images();
    if let Some(index) = crate::feature_hooks::image_index(image) {
        IMAGE_NEVER[index].store(never as u64, Relaxed);
    }
    let every = IMAGE_NEVER[..images]
        .iter()
        .fold(u64::MAX, |all, claim| all & claim.load(Relaxed));
    NEVER.store(every & !INSTALLED.load(Relaxed), Relaxed);
}

/// A family's install ran: no image's claim of it stands.
pub(crate) fn installed(family: u64) {
    INSTALLED.fetch_or(family, Relaxed);
    NEVER.fetch_and(!family, Relaxed);
}

/// Whether `family` is claimed never (tests and diagnostics).
#[cfg(test)]
pub(crate) fn claimed(family: u64) -> bool {
    NEVER.load(Relaxed) & family != 0
}

/// A byte cell that is a JavaScript value is being born.
#[inline(always)]
pub(crate) fn byte_cell_birth() {
    if NEVER.load(Relaxed) & BYTE_CELLS != 0 {
        never(
            "typedarray",
            "a typed array, Buffer or ArrayBuffer is created",
        );
    }
}

/// The empty-slot arm of an entry of the byte-cell family that creates a
/// value or serves one (a typed-array constructor, the method tower).
#[cold]
#[inline(never)]
pub(crate) fn byte_cells_not_installed() -> ! {
    never("typedarray", "a typed-array operation is reached")
}

/// The never arm: the program reached a family its compile left out.
#[cold]
#[inline(never)]
fn never(family: &'static str, what: &'static str) -> ! {
    panic!(
        "perry: {what}, but this program was compiled without the `{family}` runtime family \
         (the whole-program fact family_reach said it is never used); \
         recompile with PERRY_FACTS_FAMILY_LINK=0 and report this"
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    extern "C" fn image() {}
    extern "C" fn other_image() {}

    /// One sequence, in one test: the words are process state.
    #[test]
    fn a_claim_stands_only_when_every_image_makes_it_and_none_installs() {
        crate::test_support::isolated_test(|| {
            // Unit tests install every compiled feature on first use of a
            // hook, so the sequence runs on bits no family has.
            let (a, b) = (1u64 << 63, 1u64 << 62);
            assert_ne!(BYTE_CELLS, 0);
            assert_eq!(BYTE_CELLS & (a | b), 0);
            crate::feature_hooks::js_runtime_register_feature_installer(image);
            crate::feature_hooks::js_runtime_register_feature_installer(other_image);
            assert_eq!(crate::feature_hooks::registered_images(), 2);
            // One image of two claims: nothing is claimed.
            js_runtime_families_never((a | b) as i64, image);
            assert!(!claimed(a) && !claimed(b));
            // Again (a second thread's initialization): still nothing.
            js_runtime_families_never((a | b) as i64, image);
            assert!(!claimed(a) && !claimed(b));
            // The other image claims one of the two: that one stands.
            js_runtime_families_never(a as i64, other_image);
            assert!(claimed(a) && !claimed(b));
            // An install withdraws it, and a later claim does not bring it back.
            installed(a);
            assert!(!claimed(a));
            js_runtime_families_never(a as i64, other_image);
            js_runtime_families_never((a | b) as i64, image);
            assert!(!claimed(a) && !claimed(b));
            // An installer nothing registered claims nothing.
            extern "C" fn stranger() {}
            js_runtime_families_never(b as i64, stranger);
            assert!(!claimed(b));
            js_runtime_families_never(b as i64, other_image);
            assert!(claimed(b));
        });
    }
}
