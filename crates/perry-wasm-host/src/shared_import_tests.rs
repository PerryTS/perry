struct Imports {
    memory: *mut c_void,
    table: *mut c_void,
    base: *mut c_void,
    inc: *mut c_void,
}

unsafe extern "C" fn resolve(
    context: u64,
    _module: *const u8,
    _module_len: usize,
    name: *const u8,
    name_len: usize,
    _kind: u8,
) -> *mut c_void {
    let imports = &*(context as *const Imports);
    match std::slice::from_raw_parts(name, name_len) {
        b"memory" => imports.memory,
        b"table" => imports.table,
        b"base" => imports.base,
        b"inc" => imports.inc,
        _ => std::ptr::null_mut(),
    }
}

#[test]
fn instances_share_imported_memory_table_global_and_function() {
    let main_module = compile(MAIN_WASM).expect("compile main");
    let mut main = instantiate(&main_module).expect("instantiate main");
    fn export(main: &mut WasmInstanceHandle, name: &[u8]) -> *mut c_void {
        externals::perry_wasm_host_instance_export_extern(main, name.as_ptr().cast(), name.len())
    }
    let imports = Imports {
        memory: export(&mut main, b"memory"),
        table: export(&mut main, b"table"),
        base: export(&mut main, b"base"),
        inc: export(&mut main, b"inc"),
    };
    let side_module = compile(SIDE_WASM).expect("compile side");
    let mut side = instantiate_with_import_callbacks(
        &side_module,
        None,
        Some(resolve),
        &imports as *const Imports as u64,
    )
    .expect("instantiate side with shared externals");

    assert_eq!(
        call_export(&mut side, "readBase", &[]).unwrap(),
        [WasmVal::I32(7)]
    );
    call_export(&mut side, "bumpBase", &[]).unwrap();
    assert_eq!(
        call_export(&mut side, "readBase", &[]).unwrap(),
        [WasmVal::I32(8)]
    );
    assert_eq!(
        call_export(&mut side, "callInc", &[WasmVal::I32(41)]).unwrap(),
        [WasmVal::I32(42)]
    );
    call_export(&mut side, "store", &[WasmVal::I32(3), WasmVal::I32(99)]).unwrap();
    let (memory, len) = super::tests::memory_span(&mut main);
    assert_eq!(len, 65536);
    assert_eq!(unsafe { *memory.add(3) }, 99);
}
