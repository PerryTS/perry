// A default build that links the http, events, crypto and zlib modules together
// imports only wasi_snapshot_preview1: no module drags in the opt-in perry_net
// imports unless PERRY_WASM_NET=1 asks for them (wasi_run.py checks the linked
// module's imports for every case).
import { EventEmitter } from "node:events";
import * as crypto from "node:crypto";
import * as http from "node:http";
import * as zlib from "node:zlib";

const bus = new EventEmitter();
bus.on("ready", (text: string) => console.log("events", text));
bus.emit("ready", http.STATUS_CODES[404]);
console.log("crypto", crypto.createHash("sha256").update("perry").digest("hex"));
console.log("zlib", zlib.gunzipSync(zlib.gzipSync("perry")).toString());
